"""C3 phase 2 evaluation: freeze each student's inference setting on the official validation split, report on test.

Protocol (fixed in PREREGISTRATION.md before training):
  - each student selects (image size, NMS IoU) on the official 1,469-image validation split by mAP@0.5:0.95,
    at the standard detection confidence of 0.001, over a six-setting grid;
  - the selected setting is frozen and applied unchanged to the official 8,980-image test split, which has not
    been touched before this script runs;
  - arms are compared by their per-seed means on test; the pre-registered contrast is weighted minus plain.

Outputs phase2_eval.json and PHASE2_RESULT.md.
"""
from __future__ import annotations

import datetime as dt
import json
import os
import shutil
import statistics as st
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = Path(r"<YOLO11_ROOT>/outputs/sota_runs/dronevehicle_c3")
DV = Path(r"<DRONEVEHICLE_ROOT>")
FORK = Path(r"<FORK_ROOT>")
LOG = HERE / "phase2_progress.log"
CLASSES = ["car", "truck", "bus", "van", "freight_car"]
GRID = [(imgsz, iou) for imgsz in (640, 704) for iou in (0.5, 0.6, 0.7)]
CONF = 0.001
ARMS = ["gt_only", "plain", "weighted", "eq3"]
SEEDS = [0, 1, 2, 3]


def log(msg: str) -> None:
    line = "[%s] P2-EVAL %s" % (dt.datetime.now().strftime("%Y-%m-%d %H:%M:%S"), msg)
    print(line, flush=True)
    with LOG.open("a", encoding="utf-8") as f:
        f.write(line + "\n")


def link(src: Path, dst: Path) -> None:
    if dst.exists():
        return
    dst.parent.mkdir(parents=True, exist_ok=True)
    try:
        os.link(src, dst)
    except OSError:
        shutil.copy2(src, dst)


def ensure_eval_yamls() -> dict:
    """Link the official val and test splits once and write one data yaml per split."""
    yamls = {}
    for split, src_split in (("val", "val"), ("test", "test")):
        stems = sorted(p.stem for p in (DV / "yolo_dataset/images" / src_split).glob("*.jpg"))
        for s in stems:
            link(DV / ("yolo_dataset/images/%s/%s.jpg" % (src_split, s)), OUT / "eval" / "images" / split / ("%s.jpg" % s))
            link(DV / ("yolo_dataset_ir/images/%s/%s.jpg" % (src_split, s)), OUT / "eval" / "images_ir" / split / ("%s.jpg" % s))
            link(DV / ("yolo_dataset/labels/%s/%s.txt" % (src_split, s)), OUT / "eval" / "labels" / split / ("%s.txt" % s))
        names = "\n".join("  %d: %s" % (i, c) for i, c in enumerate(CLASSES))
        y = OUT / ("eval_%s.yaml" % split)
        y.write_text("# generated by phase2_eval.py\npath: %s\ntrain: images/%s\nval: images/%s\nnc: %d\nnames:\n%s\n"
                     % ((OUT / "eval").as_posix(), split, split, len(CLASSES), names), encoding="utf-8")
        yamls[split] = y
        log("%s split linked: %d images" % (split, len(stems)))
    return yamls


def evaluate(ckpt: Path, data_yaml: Path, imgsz: int, iou: float, tag: str) -> dict:
    from ultralytics import YOLO
    m = YOLO(str(ckpt)).val(data=str(data_yaml), imgsz=imgsz, batch=8, conf=CONF, iou=iou, device="0", verbose=False,
                            plots=False, workers=0, project=str(OUT / "eval_runs"), name=tag, exist_ok=True,
                            use_simotm="RGBT", channels=4, pairs_rgb_ir=["images", "images_ir"])
    b = m.box
    per = {CLASSES[i]: float(b.all_ap[i].mean()) for i in range(len(b.all_ap))} if len(b.all_ap) else {}
    return {"map50": float(b.map50), "map50_95": float(b.map), "per_class_map50_95": per}


def run() -> None:
    import numpy as np
    if not hasattr(np, "trapz"):
        np.trapz = np.trapezoid
    sys.path.insert(0, str(FORK))
    os.environ.setdefault("YOLO_CONFIG_DIR", str(OUT / "ultralytics_config"))
    os.environ.setdefault("WANDB_DISABLED", "true")

    yamls = ensure_eval_yamls()
    cache = HERE / "phase2_eval.json"
    res = json.loads(cache.read_text(encoding="utf-8")) if cache.exists() else {}

    for arm in ARMS:
        for seed in SEEDS:
            key = "%s_s%d" % (arm, seed)
            if key in res:
                log("%s cached" % key)
                continue
            ckpt = OUT / "students" / key / "weights" / "best.pt"
            if not ckpt.exists():
                log("%s: checkpoint missing, skipped" % key)
                continue
            best = None
            for imgsz, iou in GRID:
                m = evaluate(ckpt, yamls["val"], imgsz, iou, "%s_val_%d_%g" % (key, imgsz, iou))
                if best is None or m["map50_95"] > best["val"]["map50_95"]:
                    best = {"setting": {"imgsz": imgsz, "iou": iou, "conf": CONF}, "val": m}
            test = evaluate(ckpt, yamls["test"], best["setting"]["imgsz"], best["setting"]["iou"],
                            "%s_test_%d_%g" % (key, best["setting"]["imgsz"], best["setting"]["iou"]))
            res[key] = {**best, "test": test}
            cache.write_text(json.dumps(res, indent=2), encoding="utf-8")
            log("%s: frozen %s | val %.4f | test mAP50 %.4f mAP50-95 %.4f"
                % (key, best["setting"], best["val"]["map50_95"], test["map50"], test["map50_95"]))

    # ---- report -------------------------------------------------------------------------------------
    def arm_vals(arm, split, key="map50_95"):
        return [res["%s_s%d" % (arm, s)][split][key] for s in SEEDS if "%s_s%d" % (arm, s) in res]

    lines = ["# C3 phase 2 result: DroneVehicle student experiment (%s)" % dt.datetime.now().strftime("%Y-%m-%d %H:%M"), "",
             "Pre-registered in PREREGISTRATION.md before training. Settings frozen on the official validation split,",
             "reported on the official 8,980-image test split.", "",
             "| arm | seeds | val mAP@0.5:0.95 | test mAP@0.5 | test mAP@0.5:0.95 |", "|---|---:|---:|---:|---:|"]
    for arm in ARMS:
        v, t50, t = arm_vals(arm, "val"), arm_vals(arm, "test", "map50"), arm_vals(arm, "test")
        if not t:
            continue
        f = lambda xs: ("%.4f" % st.mean(xs)) + (" ± %.4f" % st.stdev(xs) if len(xs) > 1 else "")
        lines.append("| %s | %d | %s | %s | %s |" % (arm, len(t), f(v), f(t50), f(t)))
    w, p, g = arm_vals("weighted", "test"), arm_vals("plain", "test"), arm_vals("gt_only", "test")
    if w and p:
        d = (st.mean(w) - st.mean(p)) * 100
        lines += ["", "## Pre-registered contrast", "",
                  "- weighted minus plain on test: **%+.2f pp** mAP@0.5:0.95 (Anti-UAV reference: +2.47 pp at 5.5%% pseudo-label noise; here 39.4%%)" % d,
                  "- prediction P1 (gain materially larger than +2.47 pp): **%s**" % ("supported" if d > 2.47 else "not supported"),
                  "- stop rule (|difference| < 0.5 pp means do not add seeds): %s" % ("triggered" if abs(d) < 0.5 else "not triggered")]
        if g:
            lines += ["- plain minus GT-only: %+.2f pp; weighted minus GT-only: %+.2f pp (prediction P2: pseudo labels help at all)"
                      % ((st.mean(p) - st.mean(g)) * 100, (st.mean(w) - st.mean(g)) * 100)]
    (HERE / "PHASE2_RESULT.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    log("evaluation complete")


if __name__ == "__main__":
    import multiprocessing
    multiprocessing.freeze_support()
    run()

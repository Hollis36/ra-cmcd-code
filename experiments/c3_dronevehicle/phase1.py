"""C3 phase 1: build the DroneVehicle RGB-T student study up to the label-level gate. No student training here.

Steps
  A  build a paired RGB/IR YOLO dataset in the fork's layout using HARD LINKS (never junctions: a junction makes Ultralytics read the target's labels)
  B  partition the official train split into L (labelled, 20 percent) and U (pseudo-labelled, 80 percent) by
     contiguous 50-frame blocks with a frozen seed, so temporally adjacent frames do not straddle the split
  C  train three heterogeneous RGB-T teachers (early, mid-to-late, late fusion) on L only
  D  export teacher predictions on U
  E  class-wise WBF on U, score with Eq. 3 (M = 3), and evaluate the label-level gate against U's held-out
     human labels: reliability versus plain versus confidence-only

Gate: reliability rescoring must beat plain WBF by at least 0.3 pp mAP@0.5:0.95 on U before any student is trained.

Everything is logged to phase1_progress.log. Resumable: each step skips if its output already exists.
"""
from __future__ import annotations

import datetime as dt
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
DV = Path(r"<DRONEVEHICLE_ROOT>")
OUT = Path(r"<YOLO11_ROOT>/outputs/sota_runs/dronevehicle_c3")
FORK = Path(r"<FORK_ROOT>")
LOG = HERE / "phase1_progress.log"
CLASSES = ["car", "truck", "bus", "van", "freight_car"]
TEACHERS = {"early": "yolo11-RGBT-earlyfusion.yaml", "midlate": "yolo11-RGBT-mid-to-late-fusion.yaml", "late": "yolo11-RGBT-latefusion.yaml"}
BLOCK = 50          # frames per contiguous block, approximating a short capture run
L_FRACTION = 0.20
SEED = 20260910
EPOCHS = 100
IMGSZ = 640
BATCH = 8


def log(msg: str) -> None:
    line = "[%s] %s" % (dt.datetime.now().strftime("%Y-%m-%d %H:%M:%S"), msg)
    print(line, flush=True)
    with LOG.open("a", encoding="utf-8") as f:
        f.write(line + "\n")


def link_all(dst: Path, pairs) -> int:
    dst.mkdir(parents=True, exist_ok=True)
    n = 0
    for src in pairs:
        d = dst / src.name
        if d.exists():
            n += 1
            continue
        try:
            os.link(src, d)
        except OSError:
            shutil.copy2(src, d)
        n += 1
    return n


def step_a_b():
    """Build the paired dataset and freeze the L/U partition."""
    manifest = OUT / "partition.json"
    if manifest.exists():
        log("A/B dataset and partition exist")
        return json.loads(manifest.read_text(encoding="utf-8"))
    stems = sorted(p.stem for p in (DV / "yolo_dataset/images/train").glob("*.jpg"))
    blocks = [stems[i:i + BLOCK] for i in range(0, len(stems), BLOCK)]
    rng = np.random.default_rng(SEED)
    pick = rng.random(len(blocks)) < L_FRACTION
    L = [s for b, keep in zip(blocks, pick) for s in (b if keep else [])]
    U = [s for b, keep in zip(blocks, pick) for s in ([] if keep else b)]
    log("B partition: %d blocks of %d, L %d frames (%.1f%%), U %d frames" % (len(blocks), BLOCK, len(L), 100 * len(L) / len(stems), len(U)))

    for split, stems_ in (("L", L), ("U", U), ("val", sorted(p.stem for p in (DV / "yolo_dataset/images/val").glob("*.jpg")))):
        src_split = "val" if split == "val" else "train"
        n_rgb = link_all(OUT / "data" / "images" / split, [DV / f"yolo_dataset/images/{src_split}/{s}.jpg" for s in stems_])
        n_ir = link_all(OUT / "data" / "images_ir" / split, [DV / f"yolo_dataset_ir/images/{src_split}/{s}.jpg" for s in stems_])
        n_lab = link_all(OUT / "data" / "labels" / split, [DV / f"yolo_dataset/labels/{src_split}/{s}.txt" for s in stems_])
        log("A %s: rgb %d ir %d labels %d" % (split, n_rgb, n_ir, n_lab))

    names = "\n".join("  %d: %s" % (i, c) for i, c in enumerate(CLASSES))
    for name, train_split in (("teacher_L", "L"), ("student_U", "U")):
        (OUT / ("%s.yaml" % name)).write_text(
            "# generated by phase1.py\npath: %s\ntrain: images/%s\nval: images/val\nnc: %d\nnames:\n%s\n"
            % ((OUT / "data").as_posix(), train_split, len(CLASSES), names), encoding="utf-8")
    m = {"seed": SEED, "block": BLOCK, "l_fraction": L_FRACTION, "n_train": len(stems), "L": L, "U": U}
    manifest.parent.mkdir(parents=True, exist_ok=True)
    manifest.write_text(json.dumps(m), encoding="utf-8")
    log("A/B done; yamls written")
    return m


def step_c(name, model_yaml):
    """Train one teacher on L."""
    run_dir = OUT / "teachers" / name
    ckpt = run_dir / "weights" / "best.pt"
    results = run_dir / "results.csv"
    if ckpt.exists() and results.exists() and sum(1 for _ in results.open(encoding="utf-8")) - 1 >= EPOCHS:
        log("C teacher %s exists" % name)
        return ckpt
    if run_dir.exists():
        run_dir.rename(run_dir.with_name("%s_partial_%s" % (name, dt.datetime.now().strftime("%Y%m%d_%H%M%S"))))
    log("C training teacher %s (%s) on L" % (name, model_yaml))
    # the guard is required: without it Windows DataLoader workers re-import the module and abort with freeze_support
    code = (
        "import sys, os\n"
        "sys.path.insert(0, r'%s')\n"
        "os.environ.setdefault('YOLO_CONFIG_DIR', r'%s')\n"
        "os.environ.setdefault('WANDB_DISABLED','true')\n"
        "\n"
        "def run():\n"
        "    import numpy as np\n"
        "    np.trapz = getattr(np, 'trapz', np.trapezoid)\n"
        "    from ultralytics import YOLO\n"
        "    m = YOLO(r'%s')\n"
        "    m.train(data=r'%s', epochs=%d, imgsz=%d, batch=%d, workers=4, seed=42, optimizer='AdamW', lr0=0.001,\n"
        "            warmup_epochs=3, close_mosaic=10, deterministic=True, device='0', project=r'%s', name='%s', exist_ok=True,\n"
        "            use_simotm='RGBT', channels=4, pairs_rgb_ir=['images','images_ir'])\n"
        "\n"
        "if __name__ == '__main__':\n"
        "    import multiprocessing\n"
        "    multiprocessing.freeze_support()\n"
        "    run()\n"
    ) % (FORK.as_posix(), (OUT / "ultralytics_config").as_posix(), (FORK / "ultralytics/cfg/models/11-RGBT" / model_yaml).as_posix(),
         (OUT / "teacher_L.yaml").as_posix(), EPOCHS, IMGSZ, BATCH, (OUT / "teachers").as_posix(), name)
    script = OUT / ("_train_%s.py" % name)
    script.write_text(code, encoding="utf-8")
    with (HERE / "logs_phase1").joinpath("teacher_%s.log" % name).open("a", encoding="utf-8") as f:
        rc = subprocess.run([sys.executable, "-u", str(script)], cwd=str(OUT), stdout=f, stderr=subprocess.STDOUT,
                            creationflags=0x08000000).returncode
    if rc != 0 or not ckpt.exists():
        log("C teacher %s FAILED rc=%s" % (name, rc))
        return None
    log("C teacher %s done" % name)
    return ckpt


def main() -> None:
    (HERE / "logs_phase1").mkdir(exist_ok=True)
    log("=== C3 phase 1 start ===")
    step_a_b()
    ckpts = {}
    for name, y in TEACHERS.items():
        c = step_c(name, y)
        if c is None:
            log("aborting: teacher %s failed" % name)
            return
        ckpts[name] = c
    (OUT / "teacher_ckpts.json").write_text(json.dumps({k: str(v) for k, v in ckpts.items()}, indent=1), encoding="utf-8")
    log("=== phase 1 steps A-C complete; next: export predictions on U and run the label-level gate (phase1_gate.py) ===")


if __name__ == "__main__":
    main()

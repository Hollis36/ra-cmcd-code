"""C3 phase 2: build the three DroneVehicle student datasets and train them. See PREREGISTRATION.md.

Arms
  gt_only   L human labels only
  plain     L human labels + U pseudo labels, every box weight 1.0
  weighted  L human labels (1.0) + U pseudo labels weighted by the cluster's mean member confidence

Everything is hard-linked (never junctions: a junction makes Ultralytics read the target's labels) and every labels_scored file is asserted to have exactly
as many rows as its labels file, because the fork silently falls back to all-ones on a row-count mismatch.

Resumable: datasets and runs are skipped when already complete. Logs to phase2_progress.log.
"""
from __future__ import annotations

import datetime as dt
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = Path(r"<YOLO11_ROOT>/outputs/sota_runs/dronevehicle_c3")
FORK = Path(r"<FORK_ROOT>")
LOG = HERE / "phase2_progress.log"
CLASSES = ["car", "truck", "bus", "van", "freight_car"]
EPOCHS, IMGSZ, BATCH = 50, 640, 8
SEEDS = [0, 1, 2, 3]
ARMS = ["eq3", "plain", "weighted", "gt_only"]  # eq3 first: it is the only arm still missing
sys.path.insert(0, str(HERE))


def log(msg: str) -> None:
    line = "[%s] P2 %s" % (dt.datetime.now().strftime("%Y-%m-%d %H:%M:%S"), msg)
    print(line, flush=True)
    with LOG.open("a", encoding="utf-8") as f:
        f.write(line + "\n")


def link(src: Path, dst: Path) -> None:
    if dst.exists():
        return
    dst.parent.mkdir(parents=True, exist_ok=True)
    try:
        os.link(src, dst)
    except OSError:
        shutil.copy2(src, dst)


def build(arm: str) -> Path:
    root = OUT / ("student_%s" % arm)
    yaml = root / "data.yaml"
    if (root / "BUILT").exists():
        log("dataset %s exists" % arm)
        return yaml
    if root.exists():
        shutil.rmtree(root)
    part = json.loads((OUT / "partition.json").read_text(encoding="utf-8"))
    L, U = part["L"], part["U"]

    # pseudo labels for U at the frozen tuple
    fused_by_image: dict[str, list] = {}
    if arm != "gt_only":
        import phase1_gate as G
        ck = json.loads((OUT / "teacher_ckpts.json").read_text(encoding="utf-8"))
        t = json.loads((OUT / "wbf_tuple.json").read_text(encoding="utf-8"))["tuple"]
        dets = {n: G.load_dets(OUT / "preds" / "U" / n, n, U) for n in ck}
        for f in G.fuse(dets, U, t["iou"], t["mode"], t["min_models"], t["post_conf"]):
            fused_by_image.setdefault(f["image"], []).append(f)
        log("%s: %d pseudo boxes over %d U images" % (arm, sum(len(v) for v in fused_by_image.values()), len(fused_by_image)))

    stems = L if arm == "gt_only" else L + U
    n_boxes = n_weighted = 0
    for s in stems:
        link(OUT / "data" / "images" / ("L" if s in set(L) else "U") / ("%s.jpg" % s), root / "images" / "train" / ("%s.jpg" % s))
        link(OUT / "data" / "images_ir" / ("L" if s in set(L) else "U") / ("%s.jpg" % s), root / "images_ir" / "train" / ("%s.jpg" % s))
    Lset = set(L)
    for s in stems:
        lab = root / "labels" / "train" / ("%s.txt" % s)
        lab.parent.mkdir(parents=True, exist_ok=True)
        if s in Lset:
            src = OUT / "data" / "labels" / "L" / ("%s.txt" % s)
            rows = [l for l in src.read_text(encoding="utf-8").splitlines() if l.strip()]
            weights = [1.0] * len(rows)
        else:
            boxes = fused_by_image.get(s, [])
            rows = ["%d %.6f %.6f %.6f %.6f" % (b["cls"], *b["box"]) for b in boxes]
            if arm == "plain":
                weights = [1.0] * len(boxes)
            elif arm == "eq3":
                weights = [float(min(max(b["eq3"], 0.0), 1.0)) for b in boxes]
            else:
                weights = [float(min(max(b["conf_only"], 0.0), 1.0)) for b in boxes]
        lab.write_text("\n".join(rows) + ("\n" if rows else ""), encoding="utf-8")
        sc = root / "labels_scored" / "train" / ("%s.txt" % s)
        sc.parent.mkdir(parents=True, exist_ok=True)
        sc.write_text("\n".join("%s %.6f %.6f" % (r, w, w) for r, w in zip(rows, weights)) + ("\n" if rows else ""), encoding="utf-8")
        assert len(rows) == len(weights)
        n_boxes += len(rows)
        n_weighted += sum(1 for w in weights if w < 1.0)

    for s in sorted(p.stem for p in (OUT / "data" / "images" / "val").glob("*.jpg")):
        link(OUT / "data" / "images" / "val" / ("%s.jpg" % s), root / "images" / "val" / ("%s.jpg" % s))
        link(OUT / "data" / "images_ir" / "val" / ("%s.jpg" % s), root / "images_ir" / "val" / ("%s.jpg" % s))
        link(OUT / "data" / "labels" / "val" / ("%s.txt" % s), root / "labels" / "val" / ("%s.txt" % s))

    names = "\n".join("  %d: %s" % (i, c) for i, c in enumerate(CLASSES))
    yaml.write_text("# generated by phase2.py (arm %s)\npath: %s\ntrain: images/train\nval: images/val\nnc: %d\nnames:\n%s\n"
                    % (arm, root.as_posix(), len(CLASSES), names), encoding="utf-8")

    # every labels_scored file must match its labels file row for row, or the fork silently ignores the weights
    bad = 0
    for lab in (root / "labels" / "train").glob("*.txt"):
        sc = root / "labels_scored" / "train" / lab.name
        a = len([l for l in lab.read_text(encoding="utf-8").splitlines() if l.strip()])
        b = len([l for l in sc.read_text(encoding="utf-8").splitlines() if l.strip()])
        if a != b:
            bad += 1
    assert bad == 0, "%d labels_scored row-count mismatches in %s" % (bad, arm)
    (root / "BUILT").write_text(json.dumps({"arm": arm, "images": len(stems), "boxes": n_boxes, "weighted_boxes": n_weighted}), encoding="utf-8")
    log("%s built: %d images, %d boxes, %d with weight < 1" % (arm, len(stems), n_boxes, n_weighted))
    return yaml


def train(arm: str, seed: int, data_yaml: Path):
    name = "%s_s%d" % (arm, seed)
    run = OUT / "students" / name
    ck = run / "weights" / "best.pt"
    csv = run / "results.csv"
    if ck.exists() and csv.exists() and sum(1 for _ in csv.open(encoding="utf-8")) - 1 >= EPOCHS:
        log("student %s exists" % name)
        return ck
    if run.exists():
        run.rename(run.with_name("%s_partial_%s" % (name, dt.datetime.now().strftime("%Y%m%d_%H%M%S"))))
    log("training student %s" % name)
    code = (
        "import sys, os\n"
        "sys.path.insert(0, r'%s')\n"
        "os.environ.setdefault('YOLO_CONFIG_DIR', r'%s')\n"
        "os.environ.setdefault('WANDB_DISABLED','true')\n"
        "\n"
        "def run():\n"
        "    import numpy as np\n"
        "    np.trapz = getattr(np, 'trapz', np.trapezoid)\n"
        "    from ultralytics import YOLO\n"
        "    m = YOLO(r'%s')\n"
        "    m.train(data=r'%s', epochs=%d, imgsz=%d, batch=%d, workers=4, seed=%d, optimizer='AdamW', lr0=0.001,\n"
        "            warmup_epochs=3, close_mosaic=10, deterministic=True, amp=True, device='0',\n"
        "            project=r'%s', name='%s', exist_ok=True, verbose=False, plots=False,\n"
        "            use_simotm='RGBT', channels=4, pairs_rgb_ir=['images','images_ir'])\n"
        "\n"
        "if __name__ == '__main__':\n"
        "    import multiprocessing\n"
        "    multiprocessing.freeze_support()\n"
        "    run()\n"
    ) % (FORK.as_posix(), (OUT / "ultralytics_config").as_posix(),
         (FORK / "ultralytics/cfg/models/11-RGBT/yolo11-RGBT-latefusion.yaml").as_posix(),
         data_yaml.as_posix(), EPOCHS, IMGSZ, BATCH, seed, (OUT / "students").as_posix(), name)
    script = OUT / ("_train_%s.py" % name)
    script.write_text(code, encoding="utf-8")
    (HERE / "logs_phase2").mkdir(exist_ok=True)
    with (HERE / "logs_phase2" / ("%s.log" % name)).open("a", encoding="utf-8") as f:
        rc = subprocess.run([sys.executable, "-u", str(script)], cwd=str(OUT), stdout=f, stderr=subprocess.STDOUT,
                            creationflags=0x08000000).returncode
    if rc != 0 or not ck.exists():
        log("student %s FAILED rc=%s" % (name, rc))
        return None
    log("student %s done" % name)
    return ck


def main() -> None:
    log("=== phase 2 start (pre-registered: see PREREGISTRATION.md) ===")
    yamls = {a: build(a) for a in ARMS}
    for seed in SEEDS:
        for arm in ARMS:
            if train(arm, seed, yamls[arm]) is None:
                log("aborting after %s_s%d" % (arm, seed))
                return
    log("=== phase 2 training complete; next: freeze on val, report on the official test split ===")


if __name__ == "__main__":
    import multiprocessing
    multiprocessing.freeze_support()
    main()

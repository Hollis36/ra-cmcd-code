"""S1: rebuild the Soft-Teacher-style dataset with real (hard-linked) image files.

The June dataset cmcd_dataset_soft used directory junctions for images; Ultralytics resolves them to the
target (the headline cmcd_dataset) and reads the target's labels, so the eight submitted "Soft-Teacher-style"
seeds were actually trained on the RA-CMCD all-consensus labels. This script keeps the intended soft labels
(cmcd_dataset_soft/labels*, 1,396 boxes with mean confidence >= 0.5, confidence weights) and pairs them with
hard-linked images and human validation labels from cmcd_dataset_reloff. Then s1_students.py trains 4 seeds.
"""
from __future__ import annotations

import json
import os
import shutil
import sys
from pathlib import Path

ROOT = Path(r"<YOLO11_ROOT>/outputs/sota_runs")
SRC = ROOT / "cmcd_dataset_soft"
REF = ROOT / "cmcd_dataset_reloff"
DST = ROOT / "cmcd_dataset_soft_v2"


def mirror(dst: Path, src: Path):
    dst.mkdir(parents=True, exist_ok=True)
    n = 0
    for f in src.iterdir():
        if f.is_file():
            try:
                os.link(f, dst / f.name)
            except OSError:
                shutil.copy2(f, dst / f.name)
            n += 1
    return n


def main():
    if DST.exists():
        shutil.rmtree(DST)
    counts = {}
    for sub in ("images", "images_ir"):
        for split in ("train", "val"):
            counts[f"{sub}/{split}"] = mirror(DST / sub / split, REF / sub / split)
    for sub in ("labels", "labels_ir", "labels_scored"):
        src_sub = "labels" if sub == "labels_ir" else sub  # the June dataset has no labels_ir; it mirrors labels
        counts[f"{sub}/train"] = mirror(DST / sub / "train", SRC / src_sub / "train")
        counts[f"{sub}/val"] = mirror(DST / sub / "val", REF / sub / "val")
    boxes = sum(1 for f in (DST / "labels" / "train").glob("*.txt") for l in open(f, encoding="utf-8") if l.strip())
    rel = [float(l.split()[6]) for f in (DST / "labels_scored" / "train").glob("*.txt") for l in open(f, encoding="utf-8") if l.strip()]
    (DST / "anti_uav_cmcd_student.yaml").write_text(f"# generated by s1_build_soft_v2.py\npath: {DST.as_posix()}\ntrain: images/train\nval: images/val\nnc: 1\nnames: [drone]\n", encoding="utf-8")
    (DST / "manifest.json").write_text(json.dumps({"dataset": "soft_v2", "source_labels": str(SRC), "images_from": str(REF), "counts": counts, "train_boxes": boxes,
                                                   "weight_stats": {"min": min(rel), "mean": sum(rel) / len(rel), "max": max(rel), "n": len(rel)},
                                                   "note": "hard-linked real files; replaces the junction-based cmcd_dataset_soft whose runs trained on the wrong labels"}, indent=2), encoding="utf-8")
    print(json.dumps(counts), "| train boxes", boxes, "| weight mean", round(sum(rel) / len(rel), 3))
    # resolution check through the framework
    sys.path.insert(0, r"<FORK_ROOT>")
    os.environ.setdefault("YOLO_CONFIG_DIR", str(ROOT / "cmcd_student" / "ultralytics_config"))
    from ultralytics.data.utils import check_det_dataset, img2label_paths
    d = check_det_dataset(str(DST / "anti_uav_cmcd_student.yaml"))
    first = sorted(Path(d["train"]).glob("*.png"))[0]
    lab = img2label_paths([str(first)])[0]
    assert str(DST) in str(d["train"]) and str(DST) in lab, (d["train"], lab)
    print("framework resolves train to", d["train"], "| label", lab[-60:])


if __name__ == "__main__":
    main()
